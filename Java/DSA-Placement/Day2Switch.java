import java.util.Scanner;

class Day2Switch{
	public static void main(String args[]){
		int age = 10;
		switch(age){
			case 5:
				System.out.println("age is 5");
				break;
			case 9:
				System.out.println("Age is 9");
				break;
			case 10:
				System.out.println("Age is 10");
				break;
			default:
				System.out.println("default block");
		}
	}
}